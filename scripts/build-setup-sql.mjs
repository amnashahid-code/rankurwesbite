// Generate the single SQL Editor setup from the repository's canonical migrations.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
const dir = new URL('../supabase/migrations/', import.meta.url);
const source = readdirSync(dir).filter(f => f.endsWith('.sql')).sort()
  .map(f => `-- Source: ${f}\n${readFileSync(new URL(f, dir), 'utf8')}`).join('\n\n');
const tables = [...source.matchAll(/create table public\.(\w+)/g)].map(m => m[1]);
const functions = [...new Set([...source.matchAll(/create (?:or replace )?function public\.(\w+)/g)].map(m => m[1]))];
const quotedTables = tables.map(t => `public.${t}`).join(', ');

function splitColumns(body) {
  let depth = 0, quoted = false, start = 0;
  const parts = [];
  for (let i = 0; i < body.length; i++) {
    if (body[i] === "'") { if (quoted && body[i+1] === "'") { i++; continue; } quoted = !quoted; }
    if (quoted) continue;
    if (body[i] === '(') depth++;
    if (body[i] === ')') depth--;
    if (body[i] === ',' && depth === 0) { parts.push(body.slice(start,i).trim()); start=i+1; }
  }
  parts.push(body.slice(start).trim());
  return parts;
}

let sql = source.replace(/create table public\.(\w+) \(([\s\S]*?)\n?\);/g, (statement, table, body) => {
  const parts = splitColumns(body);
  const repairs = parts.filter(p => !/^(unique|check|primary key)\s*\(/i.test(p))
    .map(p => `alter table public.${table} add column if not exists ${p};`);
  for (const p of parts.filter(p => /^(unique|check|primary key)\s*\(/i.test(p))) {
    const columns = /^(?:unique|primary key)\s*\(([^)]+)\)/i.exec(p)?.[1];
    const name = p.startsWith('unique') ? `${table}_${columns.replaceAll(',','_').replaceAll(' ','')}_key`
      : p.startsWith('primary') ? `${table}_pkey` : `${table}_check`;
    repairs.push(`do $$ begin
 if not exists(select 1 from pg_constraint where conrelid='public.${table}'::regclass and conname='${name}') then
  alter table public.${table} add constraint ${name} ${p};
 end if;
end $$;`);
  }
  return `${statement.replace('create table','create table if not exists')}\n${repairs.join('\n')}`;
});
sql = sql.replace(/create (unique )?index (?!if not exists)/g, 'create $1index if not exists ')
  .replace(/create function /g, 'create or replace function ')
  .replace(/insert into public\.(platform_totals|app_settings)\(id\) values\(true\);/g, 'insert into public.$1(id) values(true) on conflict(id) do nothing;')
  .replace(/create trigger (\w+) (after [\s\S]*? on auth.users)/g, 'drop trigger if exists $1 on auth.users;\ncreate trigger $1 $2')
  .replace('revoke all on all tables in schema public from anon, authenticated;', `revoke all on ${quotedTables} from public, anon, authenticated;`)
  .replace(/revoke execute on all functions in schema public from public, anon, authenticated;/g, '')
  .replace(/grant all on all tables in schema public to service_role;/g, `grant all on ${quotedTables} to service_role;`)
  .replace(/grant all on all sequences in schema public to service_role;/g, 'grant usage,select on sequence public.platform_events_id_seq to service_role;')
  .replace(/grant execute on all functions in schema public to service_role;/g, '');
// Replace policies only on these app-owned tables, including overly permissive older policies.
sql = sql.replace('-- Clients can read only their own safe rows, never mutate payment/access/role state.', () => `
do $$ declare p record; begin
 for p in select tablename,policyname from pg_policies where schemaname='public'
 and tablename in (${tables.map(t=>`'${t}'`).join(',')}) loop
  execute format('drop policy %I on public.%I',p.policyname,p.tablename);
 end loop;
 -- Old column-level grants survive a table-level REVOKE; remove them explicitly.
 for p in select table_name,column_name from information_schema.columns where table_schema='public'
 and table_name in (${tables.map(t=>`'${t}'`).join(',')}) loop
  execute format('revoke all (%I) on public.%I from public,anon,authenticated',p.column_name,p.table_name);
 end loop;
end $$;
-- Clients can read only their own safe rows, never mutate payment/access/role state.`);
const header = `-- RankYourWebsite: COMPLETE PRODUCTION DATABASE SETUP
-- Run this entire file in your existing project's Supabase SQL Editor.
-- Supports a fresh database or this repository's fully/partly installed schema.
-- Repeatable: retains accounts, websites, scans, reports, payments and settings.
-- Adds missing columns with repository defaults. Incompatible existing rows/types
-- cause a transaction rollback rather than silently inventing or deleting data.
-- Replaces access policies ONLY on the 15 app-owned tables. No demo data is inserted.
-- Payment providers remain disabled on fresh installations; existing flags are preserved.
-- Generated by: node scripts/build-setup-sql.mjs
begin;
set local search_path=public,extensions;
set local lock_timeout='10s';
`;
const footer = `
-- Scope function permissions to this application, never unrelated project RPCs.
do $$ declare f record; begin
 for f in select oid::regprocedure as signature from pg_proc where pronamespace='public'::regnamespace
 and proname in (${functions.map(f=>`'${f}'`).join(',')}) loop
  execute format('revoke all on function %s from public,anon,authenticated',f.signature);
  execute format('grant execute on function %s to service_role',f.signature);
 end loop;
end $$;
notify pgrst, 'reload schema';
commit;
-- A successful run returns schemaVersion=5 and all boolean fields=true.
select public.setup_status();
`;
writeFileSync(new URL('../supabase/final-production-setup.sql', import.meta.url), header + sql + footer);
console.log('Generated supabase/final-production-setup.sql');
